import dotenv from "dotenv";
dotenv.config();
import express,{Request,Response,NextFunction} from "express";
import { connectDB } from "./config/db";
import api from "./routes/api";
const app=express();
app.use(express.json({limit:"1mb"}));
app.get("/",(_req:Request,res:Response)=>res.json({message:"E-Commerce API running"}));
app.use("/api",api);
app.use((_req:Request,res:Response)=>res.status(404).json({message:"Route not found"}));
app.use((err:any,_req:Request,res:Response,_next:NextFunction)=>{console.error(err);res.status(500).json({message:"Internal server error"});});
const port=Number(process.env.PORT)||5000;
connectDB().then(()=>app.listen(port,()=>console.log(`Server running on port ${port}`))).catch(e=>{console.error(e);process.exit(1);});
